// Copies the ABIs the web app needs from Foundry build output (out/) into abi/index.ts, typed `as const` for viem.
// Run `forge build` first.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const contracts = {
  CampaignFactory: "out/CampaignFactory.sol/CampaignFactory.json",
  Campaign: "out/Campaign.sol/Campaign.json",
};

mkdirSync("abi", { recursive: true });
const lines = ["// Generated by scripts/export-abi.mjs. Do not edit by hand.", ""];
for (const [name, file] of Object.entries(contracts)) {
  const { abi } = JSON.parse(readFileSync(file, "utf8"));
  lines.push(`export const ${name[0].toLowerCase()}${name.slice(1)}Abi = ${JSON.stringify(abi, null, 2)} as const;`, "");
}
writeFileSync("abi/index.ts", lines.join("\n"));
console.log("Wrote abi/index.ts");
